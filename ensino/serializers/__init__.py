class TuitionRuleSerializer(BaseSerializer):
    class Meta:
        model = m.TuitionRule
        fields = "__all__"
        validators = []

    def validate_product_id(self, value):
        from django.apps import apps

        request = self.context.get("request")
        snapshot = None
        if apps.is_installed("catalog"):
            from catalog import services as catalog_services
            snapshot = catalog_services.get_product_snapshot(value, entity_id=getattr(request, "entity_id", None))
        if snapshot is None:
            raise serializers.ValidationError("Choose an item of this school's catalog.")
        return value

    def validate(self, attrs):
        attrs = super().validate(attrs)
        if not attrs.get("programme", getattr(self.instance, "programme", None)) and \
                not attrs.get("grade_level", getattr(self.instance, "grade_level", None)):
            raise serializers.ValidationError({"programme": ["Choose the programme or the grade level."]})
        return attrs
