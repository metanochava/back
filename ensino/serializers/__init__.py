class StudentSerializer(BaseSerializer):
    """number is generated by the server (student_service.next_number)."""

    class Meta:
        model = m.Student
        fields = "__all__"
        validators = []
        read_only_fields = ["number"]


class EnrolmentSerializer(BaseSerializer):
    """status and programme are the server's: the status changes through the
    enrolment actions, the programme is the grade level's."""

    class Meta:
        model = m.Enrolment
        fields = "__all__"
        validators = []
        read_only_fields = ["status", "programme"]
        # empty: today (enrolment_service.enrol)
        extra_kwargs = {"enrolled_on": {"required": False}}


