class AssessmentSerializer(BaseSerializer):
    class Meta:
        model = m.Assessment
        fields = "__all__"
        validators = []

    def validate(self, attrs):
        attrs = super().validate(attrs)
        class_group = attrs.get("class_group", getattr(self.instance, "class_group", None))
        period = attrs.get("period", getattr(self.instance, "period", None))
        if class_group and period and period.academic_year_id != class_group.academic_year_id:
            raise serializers.ValidationError({"period": ["The period is not of the class's academic year."]})
        return attrs


