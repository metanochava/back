from rest_framework import serializers

from django_resaas.saas.core.base.serializers import BaseSerializer
from ensino import models as m


def _simple(model):
    # no automatic unique validators: DRF's for a conditional UniqueConstraint
    # (deleted_at IS NULL) breaks a partial update; the database constraint
    # (409 through the views' UniqueConflictMixin) and the services decide
    meta = type("Meta", (), {"model": model, "fields": "__all__", "validators": []})
    return type(f"{model.__name__}Serializer", (BaseSerializer,), {"Meta": meta})


