class TuitionRuleSerializer(BaseSerializer):
    class Meta:
        model = m.TuitionRule
        fields = "__all__"
        validators = []

    def validate_product_id(self, value):
        from django.apps import apps

        request = self.context.get("request")
        snapshot = None
        if apps.is_installed("catalog"):
            from catalog import services as catalog_services
            snapshot = catalog_services.get_product_snapshot(value, entity_id=getattr(request, "entity_id", None))
        if snapshot is None:
            raise serializers.ValidationError("Choose an item of this school's catalog.")
        return value

    def validate(self, attrs):
        attrs = super().validate(attrs)
        if not attrs.get("programme", getattr(self.instance, "programme", None)) and \
                not attrs.get("grade_level", getattr(self.instance, "grade_level", None)):
            raise serializers.ValidationError({"programme": ["Choose the programme or the grade level."]})
        return attrs


class TimetableSlotSerializer(BaseSerializer):
    """academic_year is the class's. A class, its teacher or its room is never
    in two overlapping slots on a weekday (timetable_service.clashes); every
    relation is of the request's Entity."""

    class Meta:
        model = m.TimetableSlot
        fields = "__all__"
        validators = []
        read_only_fields = ["academic_year"]

    def validate(self, attrs):
        from academica.services import timetable_service

        attrs = super().validate(attrs)
        request = self.context.get("request")
        entity_id = str(getattr(request, "entity_id", "") or "")
        current = self.instance
        get = lambda key: attrs.get(key, getattr(current, key, None))  # noqa: E731
        for key in ("class_group", "subject", "teacher"):
            obj = attrs.get(key)
            if obj is not None and entity_id and str(obj.entity_id) != entity_id:
                raise serializers.ValidationError({key: ["Does not belong to the current entity."]})
        starts_at, ends_at = get("starts_at"), get("ends_at")
        if starts_at and ends_at and ends_at <= starts_at:
            raise serializers.ValidationError({"ends_at": ["The end must be after the start."]})
        class_group = get("class_group")
        if class_group is None:
            return attrs
        teacher = get("teacher")
        found = timetable_service.clashes(
            academic_year_id=class_group.academic_year_id, weekday=get("weekday"), starts_at=starts_at,
            ends_at=ends_at, class_group_id=class_group.id, teacher_id=teacher.id if teacher else None,
            room_id=get("room_id"), exclude_id=current.id if current else None,
        )
        messages = {"class_group": "The class already has a lesson at this time.",
                    "teacher": "The teacher already has a lesson at this time.",
                    "room": "The room is already taken at this time."}
        if found:
            key = next(iter(found))
            field = {"class_group": "starts_at", "teacher": "teacher", "room": "room_id"}[key]
            raise serializers.ValidationError({field: [messages[key]]})
        attrs["academic_year"] = class_group.academic_year
        return attrs


class PriorSchoolingSerializer(BaseSerializer):
    class Meta:
        model = m.PriorSchooling
        fields = "__all__"
        validators = []

    def validate_student(self, student):
        request = self.context.get("request")
        if request is not None and str(student.entity_id) != str(getattr(request, "entity_id", "")):
            raise serializers.ValidationError("Does not belong to the current entity.")
        return student
